/*
===============================================================================
Change Over Time Analysis:
    - To track trends, growth, and changes in key metrics over time.
    - For time-series analysis and identifying seasonality.
    - To measure growth or decline over specific periods.
    - Date Functions: DATEPART(), DATETRUNC(), FORMAT()
    - Aggregate Functions: SUM(), COUNT(), AVG()
===============================================================================
*/

-- Analyse sales performance over time
-- Quick Date Functions
SELECT
    YEAR(order_date) order_year,
    MONTH(order_date) order_month,
    SUM(sales_amount) total_sales,
    COUNT(DISTINCT customer_key) total_customers
FROM gold.fact_sales 
WHERE order_date IS NOT NULL
GROUP BY YEAR(order_date), MONTH(order_date)
ORDER BY YEAR(order_date), MONTH(order_date) 

-- Using DATETRUNC()
SELECT
    DATETRUNC(month,order_date) order_date, --DATETRUNC(year,order_date) order_date
    SUM(sales_amount) total_sales,
    COUNT(DISTINCT customer_key) total_customers
FROM gold.fact_sales 
WHERE order_date IS NOT NULL
GROUP BY DATETRUNC(month,order_date)
ORDER BY DATETRUNC(month,order_date)

/*
===============================================================================
Cumulative Analysis:
    - To calculate running totals or moving averages for key metrics.
    - To track performance over time cumulatively.
    - Useful for growth analysis or identifying long-term trends.
    - Window Functions: SUM() OVER(), AVG() OVER()
===============================================================================
*/

-- Calculate the total sales per month 
-- and the running total of sales over time 

SELECT
    order_date,
    total_sales,
    SUM(total_sales) OVER (ORDER BY order_date) AS runnig_total_sales,
    AVG(avg_price) OVER (ORDER BY order_date) AS moving_avrg_sales
FROM(
    SELECT
        DATETRUNC(month,order_date) order_date, 
        SUM(sales_amount) total_sales,
        AVG(price) avg_price
    FROM gold.fact_sales 
    WHERE order_date IS NOT NULL
    GROUP BY DATETRUNC(month,order_date) 
