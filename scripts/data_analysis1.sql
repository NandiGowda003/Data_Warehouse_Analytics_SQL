 -- What is the distribution of sold items across countries?
 SELECT 
     c.country,
     COUNT(f.quantity) AS total_items_sold
 FROM gold.dim_customers c
 LEFT JOIN gold.fact_sales f
 ON c.customer_key = f.customer_key
 GROUP BY c.country
 ORDER BY total_items_sold DESC;


 /*
 ===============================================================================
 Ranking Analysis:
  - To rank data based on specific metrics and identify top performers.
     - For understanding the best and worst performers in the dataset.
     - Window Ranking Functions: RANK(), DENSE_RANK(), ROW_NUMBER()
     - GROUP BY, ORDER BY
 ===============================================================================
 */

 -- Which 5 products Generating the Highest Revenue?
 -- 1.simple mothod
SELECT TOP 5
   p.product_name,
   SUM(f.sales_amount) AS total_revenue
FROM gold.dim_products p
LEFT JOIN gold.fact_sales f
    ON p.product_key = f.product_key
GROUP BY p.product_name
ORDER BY total_revenue DESC;

-- 2. using window function & Subquery
SELECT *
FROM (
    SELECT
       p.product_name,
       SUM(f.sales_amount) AS total_revenue,
       RANK() OVER (ORDER BY SUM(f.sales_amount) DESC) AS rank_products
    FROM gold.dim_products p
    LEFT JOIN gold.fact_sales f
        ON p.product_key = f.product_key
    GROUP BY p.product_name
) t WHERE rank_products <= 5;

-- What are the 5 worst-performing products in terms of sales?
SELECT TOP 5
    p.product_name,
   SUM(f.sales_amount) AS total_revenue
FROM gold.dim_products p
LEFT JOIN gold.fact_sales f
    ON p.product_key = f.product_key
WHERE f.sales_amount IS NOT NULL
GROUP BY p.product_name
ORDER BY total_revenue;

-- Find the top 10 customers who have generated the highest revenue 
